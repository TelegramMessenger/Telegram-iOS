#!/usr/bin/env python3
"""Generates <lang>.lproj/AppShortcuts.strings from the Intents.Shortcut.* keys.

App Shortcuts (Spotlight, Siri, Shortcuts app) are read by iOS from the app bundle at build
time, so they can't use the langpack Telegram downloads at runtime. The source strings live
in en.lproj/Localizable.strings under "Intents.Shortcut.*"; this script turns them, and their
translations, into the static "AppShortcuts" table that AppShortcuts.swift references.

Usage (from any directory):
    UpdateAppShortcutsLocalizations.py [--translations DIR] [--check]

  --translations DIR  Directory with one <lang>.strings file per language, in the same format
                      as Localizable.strings (e.g. langpack exports). A language is written only
                      if it has every Intents.Shortcut.* key; otherwise it falls back to English.
  --check             Only verify that the phrases in AppShortcuts.swift match the English
                      strings and that the generated files are up to date.
"""

import argparse
import os
import re
import sys

APP_DIR = os.path.dirname(os.path.abspath(__file__))
SWIFT_FILE = os.path.join(APP_DIR, "AppShortcuts.swift")
PREFIX = "Intents.Shortcut."
APP_NAME_TOKEN = "${applicationName}"

ENTRY_RE = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', re.M)


def read_strings(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    return {k: v for k, v in ENTRY_RE.findall(text) if k.startswith(PREFIX)}


def to_phrase(value, key, lang):
    if value.count("%@") != 1:
        raise SystemExit(f"{lang}: {key} must contain exactly one %@ (the app name): {value!r}")
    return value.replace("%@", APP_NAME_TOKEN)


def swift_phrases():
    with open(SWIFT_FILE, encoding="utf-8") as f:
        text = f.read()
    return {p.replace("\\(.applicationName)", APP_NAME_TOKEN)
            for p in re.findall(r'"([^"]*\\\(\.applicationName\)[^"]*)"', text)}


def render(english, translated):
    lines = [
        "/* Generated by UpdateAppShortcutsLocalizations.py from the Intents.Shortcut.* strings. Do not edit. */",
        "",
    ]
    for key in sorted(english):
        if key.endswith(".Title"):
            lines.append(f'"{key}" = "{translated[key]}";')
    lines.append("")
    for key in sorted(english):
        if ".Phrase" in key:
            source = to_phrase(english[key], key, "en")
            lines.append(f'"{source}" = "{to_phrase(translated[key], key, "translation")}";')
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--translations")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    english = read_strings(os.path.join(APP_DIR, "en.lproj", "Localizable.strings"))
    if not english:
        raise SystemExit("No Intents.Shortcut.* keys in en.lproj/Localizable.strings")

    expected = {to_phrase(v, k, "en") for k, v in english.items() if ".Phrase" in k}
    actual = swift_phrases()
    if expected != actual:
        raise SystemExit(
            "Phrases in AppShortcuts.swift don't match en.lproj/Localizable.strings:\n"
            f"  only in Swift: {sorted(actual - expected)}\n"
            f"  only in strings: {sorted(expected - actual)}"
        )

    outputs = {"en": render(english, english)}
    if args.translations:
        for lproj in sorted(os.listdir(APP_DIR)):
            if not lproj.endswith(".lproj") or lproj in ("en.lproj", "Base.lproj"):
                continue
            lang = lproj[: -len(".lproj")]
            source = os.path.join(args.translations, f"{lang}.strings")
            if not os.path.exists(source):
                print(f"{lang}: no translations file, keeping current output")
                continue
            translated = read_strings(source)
            missing = sorted(set(english) - set(translated))
            if missing:
                print(f"{lang}: missing {', '.join(missing)}; falls back to English")
                continue
            outputs[lang] = render(english, translated)

    stale = []
    for lang, content in outputs.items():
        path = os.path.join(APP_DIR, f"{lang}.lproj", "AppShortcuts.strings")
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == content:
            continue
        if args.check:
            stale.append(path)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print(f"wrote {os.path.relpath(path, APP_DIR)}")
    if stale:
        raise SystemExit("Out of date, run UpdateAppShortcutsLocalizations.py:\n  " + "\n  ".join(stale))


if __name__ == "__main__":
    main()
