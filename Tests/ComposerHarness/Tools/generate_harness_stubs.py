#!/usr/bin/env python3
"""Emit trapping stubs for every member of a protocol the harness does not implement by hand.

The compiler is the checker, not this script. A member it misses becomes a conformance error; a
member it emits twice becomes a redeclaration error. So a regex parse is adequate, and the build
tells you when it is not.

Usage:
  python3 Tests/ComposerHarness/Tools/generate_harness_stubs.py \
      --source submodules/AccountContext/Sources/AccountContext.swift \
      --protocol SharedAccountContext \
      --conformer HarnessSharedAccountContext \
      --exclude currentPresentationData,immediateExperimentalUISettings \
      > Tests/ComposerHarness/AppContext/HarnessSharedAccountContext+Generated.swift
"""
import argparse
import re
import sys

MEMBER = re.compile(r"^    (var|func)\s+([A-Za-z_][A-Za-z0-9_]*)\s*(.*)$")
GET_SET = re.compile(r"\{\s*get(\s+set)?\s*\}\s*$")
IMPORT = re.compile(r"^import\s+([A-Za-z_][A-Za-z0-9_]*)\s*$", re.M)


def protocol_body(text, name):
    start = re.search(r"^public protocol %s\s*:[^\n]*\{$" % re.escape(name), text, re.M)
    if start is None:
        sys.exit("protocol %s not found" % name)
    body, depth = [], 1
    for line in text[start.end():].split("\n"):
        depth += line.count("{") - line.count("}")
        if depth <= 0:
            return body
        body.append(line)
    sys.exit("unterminated protocol %s" % name)


def declarations(body):
    """Yield (kind, name, rest) with MULTI-LINE declarations joined.

    The first version of this read one line at a time, so every wrapped `func foo(\n  a: A,\n)`
    emitted the truncated garbage `public func foo( {` — and two wrapped overloads of the same
    name both collapsed to `foo()`, which then failed as an invalid redeclaration. Parameter
    lists wrap freely in this protocol, so the join is not optional.
    """
    index = 0
    while index < len(body):
        line = body[index]
        match = MEMBER.match(line)
        if match is None:
            index += 1
            continue
        kind, name, rest = match.groups()
        # Accumulate until the parameter list closes. A `var` has no parens, so this is a no-op
        # for it; `depth` counts only round brackets, because a trailing `{ get }` is stripped
        # later and a closure type's braces never appear unbalanced within one declaration.
        depth = rest.count("(") - rest.count(")")
        while depth > 0 and index + 1 < len(body):
            index += 1
            continuation = body[index].strip()
            rest = rest.rstrip() + " " + continuation
            depth += continuation.count("(") - continuation.count(")")
        yield kind, name, " ".join(rest.split())
        index += 1


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--source", required=True)
    p.add_argument("--protocol", required=True)
    p.add_argument("--conformer", required=True)
    p.add_argument("--exclude", default="")
    args = p.parse_args()

    excluded = set(n for n in args.exclude.split(",") if n)
    text = open(args.source).read()

    out = []
    out.append("// GENERATED by Tests/ComposerHarness/Tools/generate_harness_stubs.py. Do not edit.")
    out.append("// Regenerate when %s changes; the build breaking is the intended notice:" % args.protocol)
    out.append("//")
    out.append("//   python3 Tests/ComposerHarness/Tools/generate_harness_stubs.py \\")
    out.append("//     --source %s \\" % args.source)
    out.append("//     --protocol %s --conformer %s \\" % (args.protocol, args.conformer))
    out.append("//     --exclude %s \\" % (args.exclude or "''"))
    out.append("//     > Tests/ComposerHarness/AppContext/%s+Generated.swift" % args.conformer)
    out.append("//")
    out.append("// Every member here TRAPS and names itself. A stub returning a plausible constant is")
    out.append("// indistinguishable from a correct answer at the call site, which has already cost this")
    out.append("// project five debugging sessions. A path that becomes reached must say so.")
    # The generated file must see every type the protocol's signatures mention, which is exactly
    # the set the protocol's OWN source imports. Copying that list is both complete and
    # self-maintaining; a hand-kept list silently rots when the protocol grows a new type.
    seen = set()
    for module in IMPORT.findall(text) + ["Postbox", "AccountContext"]:
        if module in seen:
            continue
        seen.add(module)
        out.append("import %s" % module)
    out.append("")
    out.append("extension %s {" % args.conformer)

    emitted = 0
    for kind, name, rest in declarations(protocol_body(text, args.protocol)):
        if name in excluded:
            continue
        trap = 'fatalError("harness: %s.%s is not provided")' % (args.protocol, name)
        if kind == "var":
            signature = GET_SET.sub("", ("var %s %s" % (name, rest))).rstrip()
            out.append("    public %s {" % signature)
            out.append("        %s" % trap)
            out.append("    }")
        else:
            signature = ("func %s%s" % (name, rest)).rstrip()
            out.append("    public %s {" % signature)
            out.append("        %s" % trap)
            out.append("    }")
        emitted += 1
    out.append("}")
    sys.stderr.write("emitted %d stubs for %s\n" % (emitted, args.protocol))
    print("\n".join(out))


if __name__ == "__main__":
    main()
