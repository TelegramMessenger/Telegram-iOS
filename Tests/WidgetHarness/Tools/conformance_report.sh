#!/bin/zsh
# The conformance set's report (widget-sandbox v0.1.0, conformance/CLIENTS.md): judges the run file that the last
# `bazel test //Tests/WidgetHarness:WidgetHarnessTests` wrote (ConformanceSetTests, into its undeclared outputs) with
# the vendored tools/report.mjs, into Tests/WidgetHarness/Conformance/report. With --record it also replaces the
# committed baseline with the run's (an improvement must be recorded; a regression must be fixed, not recorded).
# Run from anywhere inside the worktree; needs Node >= 18.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
BZL=./build-input/bazel-9.2.0-darwin-arm64
# `bazel info` answers for the default configuration: a run under Make.py's flags (-c dbg …) writes its outputs under
# another testlogs tree, which WIDGET_HARNESS_TESTLOGS names (`bazel info -c dbg --ios_multi_cpus=sim_arm64 bazel-testlogs`).
LOGS=${WIDGET_HARNESS_TESTLOGS:-$($BZL info bazel-testlogs 2>/dev/null)}
OUTPUTS="$LOGS/Tests/WidgetHarness/WidgetHarnessTests/test.outputs"
STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT
# The iOS test runner leaves the undeclared outputs as a directory; a zipped one is unpacked.
if [[ -d "$OUTPUTS/conformance" ]]; then
    cp -R "$OUTPUTS/conformance" "$STAGE/conformance"
elif [[ -f "$OUTPUTS/outputs.zip" ]]; then
    unzip -q -o "$OUTPUTS/outputs.zip" -d "$STAGE"
fi
chmod -R u+w "$STAGE"
RUN="$STAGE/conformance/ios-telegram-native.json"
if [[ ! -f "$RUN" ]]; then
    echo "no run file under $OUTPUTS: run the harness's Tier 1 tests (ConformanceSetTests) first"
    exit 1
fi
OUT=Tests/WidgetHarness/Conformance/report
rm -rf "$OUT"
mkdir -p "$OUT"
node third-party/widget-sandbox/conformance/tools/report.mjs --out "$OUT" "$RUN"
# The pixel diffs are regenerated by every report; only the verdicts are kept.
rm -rf "$OUT/diffs"
if [[ "${1:-}" == "--record" ]]; then
    cp "$STAGE/conformance/baseline.new.json" Tests/WidgetHarness/Conformance/baseline.json
    echo "recorded Tests/WidgetHarness/Conformance/baseline.json"
fi
