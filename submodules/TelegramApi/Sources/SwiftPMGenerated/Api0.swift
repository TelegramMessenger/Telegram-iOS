let tlSwiftSchemaHash: UInt64 = 0x2b8255422566d37c

/// Accessor offsets are compiled into clients (`@_alwaysEmitIntoClient`). This check is too:
/// a client left over from another generation (an incremental non-Bazel build) carries the
/// old literal and traps here instead of reading fields at stale offsets.
@_alwaysEmitIntoClient public func tlVerifyClientLayout() {
    if tlSchemaHashForClients() != 0x2b8255422566d37c {
        preconditionFailure("TelegramApi was regenerated; rebuild its clients (stale inlined field offsets)")
    }
}

@inline(never) public func tlSchemaHashForClients() -> UInt64 {
    return tlSwiftSchemaHash
}

public extension Api {
    static func parse(_ buffer: Buffer) -> Any? {
        let reader = BufferReader(buffer)
        if let signature = reader.readInt32() {
            return parse(reader, signature: signature)
        }
        return nil
    }

    static func parse(_ reader: BufferReader, signature: Int32) -> Any? {
        switch signature {
        case -1471112230:
            return reader.readInt32()
        case 570911930:
            return reader.readInt64()
        case 571523412:
            return reader.readDouble()
        case 0x0929C32F:
            return parseInt256(reader)
        case -1255641564:
            return parseString(reader)
        default:
            return tlParseTopLevel(reader, signature: signature)
        }
    }

    static func parseVector<T>(_ reader: BufferReader, elementSignature: Int32, elementType: T.Type) -> [T]? {
        if let count = reader.readInt32() {
            var array = [T]()
            var i: Int32 = 0
            while i < count {
                var signature = elementSignature
                if elementSignature == 0 {
                    if let unboxedSignature = reader.readInt32() {
                        signature = unboxedSignature
                    } else {
                        return nil
                    }
                }
                if elementType == Buffer.self {
                    if let item = parseBytes(reader) as? T {
                        array.append(item)
                    } else {
                        return nil
                    }
                } else {
                    if let item = Api.parse(reader, signature: signature) as? T {
                        array.append(item)
                    } else {
                        return nil
                    }
                }
                i += 1
            }
            return array
        }
        return nil
    }

    static func serializeObject(_ object: Any, buffer: Buffer, boxed: Swift.Bool) {
        if let object = object as? TLObjectBacked {
            object.serialize(buffer, boxed)
        }
    }
}
