import Foundation

/// Global Constraint 6. An unclimbed rung TRAPS, naming itself. It never returns a plausible
/// default: every one of the five hands-on defects in the prior programme was a silent wrong
/// answer that ~3,000 green tests could not distinguish from a real one.
public func richTextEngineUnimplemented(_ member: String,
                                        rung: String,
                                        file: StaticString = #fileID,
                                        line: UInt = #line) -> Never {
    preconditionFailure("RichTextEngineEditor: \(member) is not implemented — it lands at \(rung).",
                        file: file, line: line)
}
