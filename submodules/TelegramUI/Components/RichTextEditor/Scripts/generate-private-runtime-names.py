#!/usr/bin/env python3
"""Generates Sources/RichTextInputDecObjC/include/TGPrivateRuntimeNames.h from
Scripts/private-runtime-names.txt.

Every private UIKit name the editor reaches at run time (a class, protocol, selector or ivar name)
lives in that list and nowhere else in the shipping sources. The header stores each one encoded
(every UTF-8 byte XOR 0x5A, the encoding `ObfuscatedStrings` in RichTextEditorUIKit already uses), so
no plain private name reaches the binary, and exposes it as a function named after it:
`TGPN_<name>()`, with every ':' spelled '_' (`_canHandleResponderAction:` is
`TGPN__canHandleResponderAction_()`).

Usage: Scripts/generate-private-runtime-names.py   (run from the package root, or anywhere)
`PrivateRuntimeNamesTests` fails when the header and the list disagree.

       Scripts/generate-private-runtime-names.py --encode-bytes FILE
prints FILE's bytes in the same encoding, as the rows of a C byte array (16 per line). That is how
the two embedded contract tables are stored (`Generated/TGRichTextInputDecContractData.m`,
`RichTextInputDecUpstream/Generated/RichTextInputDecUpstreamPristineManifest.m`): regenerating
either means pasting this output between the braces of its array. `TGPrivateRuntimeDataDecode`
reverses it, and `VendorSnapshotIntegrityTests` pins the decoded bytes.
"""
import os
import re
import sys

KEY = 0x5A
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIST = os.path.join(ROOT, 'Scripts', 'private-runtime-names.txt')
HEADER = os.path.join(ROOT, 'Sources', 'RichTextInputDecObjC', 'include', 'TGPrivateRuntimeNames.h')
NAME = re.compile(r'^[A-Za-z_][A-Za-z0-9_]*(?::[A-Za-z0-9_]*)*:?$')


def read_names():
    names = []
    for line in open(LIST, encoding='utf-8'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        if not NAME.match(line):
            sys.exit(f'not a runtime name: {line!r}')
        names.append(line)
    if len(set(names)) != len(names):
        sys.exit('the list names something twice')
    functions = [function_name(name) for name in names]
    if len(set(functions)) != len(functions):
        sys.exit('two names map to one function name')
    return sorted(names)


def function_name(name):
    return 'TGPN_' + name.replace(':', '_')


def encode_bytes(path):
    data = open(path, 'rb').read()
    for start in range(0, len(data), 16):
        print('    ' + ' '.join(f'0x{b ^ KEY:02x},' for b in data[start:start + 16]))


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--encode-bytes':
        encode_bytes(sys.argv[2])
        return
    if len(sys.argv) != 1:
        sys.exit(__doc__)
    names = read_names()
    lines = [
        '// GENERATED by Scripts/generate-private-runtime-names.py from Scripts/private-runtime-names.txt.',
        '// DO NOT HAND-EDIT: add the name to the list and regenerate. PrivateRuntimeNamesTests checks the two',
        '// agree and that no shipping source spells one of these names in plain text.',
        '//',
        '// Each function returns one private UIKit name, decoded once (every UTF-8 byte XOR 0x5A, the',
        '// encoding RichTextEditorUIKit\'s ObfuscatedStrings uses). The function is named after the name',
        '// with every \':\' spelled \'_\'. Only the encoded bytes reach the binary.',
        '#import <TargetConditionals.h>',
        '#import <Foundation/Foundation.h>',
        '',
        'NS_ASSUME_NONNULL_BEGIN',
        '',
        '/// Decodes one entry of this table. Exposed for the macro below and for tests.',
        'FOUNDATION_EXPORT NSString *TGPrivateRuntimeNameDecode(const uint8_t *bytes, size_t length);',
        '',
        '/// Decodes a byte array stored with the same encoding (the embedded contract tables).',
        'FOUNDATION_EXPORT NSData *TGPrivateRuntimeDataDecode(const uint8_t *bytes, size_t length);',
        '',
        '#define TG_PRIVATE_RUNTIME_NAME(function, ...) \\',
        '    static inline NSString *function(void) { \\',
        '        static NSString *value; \\',
        '        static dispatch_once_t once; \\',
        '        dispatch_once(&once, ^{ \\',
        '            static const uint8_t bytes[] = { __VA_ARGS__ }; \\',
        '            value = TGPrivateRuntimeNameDecode(bytes, sizeof(bytes)); \\',
        '        }); \\',
        '        return value; \\',
        '    }',
        '',
    ]
    for name in names:
        encoded = ', '.join(f'0x{b ^ KEY:02x}' for b in name.encode('utf-8'))
        lines.append(f'TG_PRIVATE_RUNTIME_NAME({function_name(name)}, {encoded})')
    lines += ['', 'NS_ASSUME_NONNULL_END', '']
    with open(HEADER, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f'{len(names)} names -> {os.path.relpath(HEADER, ROOT)}')


if __name__ == '__main__':
    main()
