#!/usr/bin/env python3
"""Writes IDL/cssom-properties.webidl and Sources/DOM/CSSProperties.inc from IDL/css-properties.txt.

CSSOM's CSSStyleProperties: for every supported property, the camel-cased attribute, and for a -webkit- property the
webkit-cased one too ("CSS property to IDL attribute", with and without the lowercase-first flag). The dashed attribute
(`style['background-color']`) is the generator's: WidgetIDL adds it for a [CSSProperty] whose name has a dash.
`float` has no camel-cased attribute here (an IDL keyword): it is `cssFloat`, CSSStyleDeclaration's own.
Run from the WidgetRuntime directory: python3 IDL/generate-css-properties.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def to_attribute(prop, lowercase_first):
    out = []
    upper_next = False
    chars = prop[1:] if lowercase_first else prop
    for c in chars:
        if c == "-":
            upper_next = True
        elif upper_next:
            out.append(c.upper())
            upper_next = False
        else:
            out.append(c)
    return "".join(out)


def main():
    with open(os.path.join(HERE, "css-properties.txt")) as f:
        props = [line.strip() for line in f if line.strip() and not line.startswith("#")]
    if len(set(props)) != len(props):
        sys.exit("css-properties.txt: duplicate names")
    for p in props:
        if p != p.lower():
            sys.exit(f"css-properties.txt: {p} is not lower case")
    lines = [
        "// Generated by IDL/generate-css-properties.py from IDL/css-properties.txt: do not edit.",
        "// CSSOM's CSSStyleProperties (https://drafts.csswg.org/cssom/#cssstyleproperties).",
        "partial interface CSSStyleDeclaration {",
    ]
    for p in props:
        names = []
        if p.startswith("-webkit-"):
            names = [to_attribute(p, False), to_attribute(p, True)]
        elif p != "float":
            names = [to_attribute(p, False)]
        for n in names:
            lines.append(f"  [CEReactions, CSSProperty={p}] attribute [LegacyNullToEmptyString] DOMString {n};")
    lines.append("};")
    with open(os.path.join(HERE, "cssom-properties.webidl"), "w") as f:
        f.write("\n".join(lines) + "\n")
    inc = ["// Generated by IDL/generate-css-properties.py from IDL/css-properties.txt: do not edit. Sorted (bytewise)."]
    for p in sorted(props):
        inc.append(f'"{p}",')
    with open(os.path.join(ROOT, "Sources", "DOM", "CSSProperties.inc"), "w") as f:
        f.write("\n".join(inc) + "\n")
    print(f"{len(props)} properties")


main()
