#!/usr/bin/env python3
"""Writes Sources/Host/ProfileTables.inc from third-party/widget-sandbox/profile/profile.json (V5c plan, Task 1).

Profile 1's tables as sorted constexpr arrays of std::string_view, one per table, for Sources/Host/Profile.cpp's binary
searches. Only the CSS tables and the image types for now (CSS.supports); V4's validator adds the HTML, SVG, event and
canvas tables beside them, in the same form. Tests/ProfileTablesTests.cpp checks the file against the JSON.
Run from the WidgetRuntime directory: python3 IDL/generate-profile-tables.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
PROFILE = os.path.join(ROOT, "..", "..", "..", "..", "..", "third-party", "widget-sandbox", "profile", "profile.json")
OUT = os.path.join(ROOT, "Sources", "Host", "ProfileTables.inc")


def array(name, entries):
    entries = sorted(set(entries))
    lines = ["inline constexpr std::string_view %s[] = {" % name]
    for entry in entries:
        lines.append('    "%s",' % entry.replace("\\", "\\\\").replace('"', '\\"'))
    lines.append("};")
    return "\n".join(lines)


def main():
    with open(PROFILE, encoding="utf-8") as f:
        profile = json.load(f)
    tables = profile["tables"]
    css = tables["css"]
    out = [
        "// Generated by IDL/generate-profile-tables.py from third-party/widget-sandbox/profile/profile.json (profile %d)."
        % profile["profile"],
        "// Do not edit: change the vendored JSON and run the generator. Included by Sources/Host/Profile.cpp.",
        "",
        array("kCSSProperties", css["properties"]),
        array("kCSSFunctions", css["functions"]),
        array("kCSSUnits", css["units"]),
        array("kCSSDisplayValues", css["values"]["display"]),
        array("kCSSPositionValues", css["values"]["position"]),
        array("kCSSPositionRewrites", css["rewrite"]["position"].keys()),
        array("kCSSOverflowRewrites", css["rewrite"]["overflow"].keys()),
        array("kCSSFilterFunctions", css["filterFunctions"]),
        array("kCSSTransform3D", css["transform3d"]),
        array("kCSSGenericFonts", css["fonts"]["generic"]),
        array("kCSSPseudoClasses", list(css["pseudoClasses"]) + list(css["pseudoRewrite"].keys())),
        array("kCSSPseudoElements", css["pseudoElements"]),
        array("kImageTypes", tables["images"]),
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
