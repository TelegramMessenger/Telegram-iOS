#!/usr/bin/env python3
"""Writes Sources/Host/ProfileTables.inc from third-party/widget-sandbox/profile/profile.json (V5c plan, Task 1).

Profile 1's tables as sorted constexpr arrays, one per table, for Sources/Host/Profile.cpp's binary searches: the CSS
tables, the image types, and (V4) the HTML and SVG tables, the at-rules and media tables, the font aliases, fallbacks
and default, and the rewrites. Two lists the reference keeps outside profile.json are constants here, each citing its
source line. Tests/ProfileTablesTests.cpp checks the file against the JSON.
Run from the WidgetRuntime directory: python3 IDL/generate-profile-tables.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
PROFILE = os.path.join(ROOT, "..", "..", "..", "..", "..", "third-party", "widget-sandbox", "profile", "profile.json")
OUT = os.path.join(ROOT, "Sources", "Host", "ProfileTables.inc")


def array(name, entries):
    entries = sorted(set(entries))
    lines = ["inline constexpr std::string_view %s[] = {" % name]
    for entry in entries:
        lines.append('    "%s",' % entry.replace("\\", "\\\\").replace('"', '\\"'))
    lines.append("};")
    return "\n".join(lines)


def pairs(name, entries, value_type="std::string_view", value=lambda v: '"%s"' % v):
    """A sorted array of {key, value} pairs, keyed by the (lower-case) first element."""
    lines = ["inline constexpr %s %s[] = {" % ("NamedElementAction" if value_type == "ElementAction" else "NamePair", name)]
    for key, entry in sorted(entries):
        lines.append('    {"%s", %s},' % (key, value(entry)))
    lines.append("};")
    return "\n".join(lines)


# widget-sandbox v0.1.0 packages/core/src/host/css-sanitizer.ts:62-72 (isTextAttr): the attributes strict attr() may
# read and the text budgets charge, besides data-* and aria-*.
TEXT_ATTRIBUTES = ["value", "placeholder", "alt", "label", "title"]
# widget-sandbox v0.1.0 packages/core/src/host/allowlist.ts:63-66 (CSS_VALUE_ATTRS): the SVG attributes whose value is
# a CSS value, judged as one.
CSS_VALUED_SVG_ATTRIBUTES = ["fill", "stroke", "filter", "mask", "clip-path", "marker", "marker-start", "marker-mid",
                             "marker-end", "cursor", "color", "flood-color", "lighting-color", "stop-color"]
ACTIONS = {"keep": "ElementAction::Keep", "span": "ElementAction::Span", "div": "ElementAction::Div",
           "drop": "ElementAction::Drop"}


def ua_stylesheet(text):
    """The profile's UA stylesheet for the master sheet: each `:where(X)` written as X (the master sheet already loses to
    every author rule, which is what `:where()` does; V2b plan, Task 2). The `@layer tw-ua{…}` wrapper is kept: in the
    master it is an origin above litehtml's own rules, which `revert` skips (twidget edit 41)."""
    return re.sub(r":where\(((?:[^()]|\([^()]*\))*)\)", r"\1", text)


def main():
    with open(PROFILE, encoding="utf-8") as f:
        profile = json.load(f)
    tables = profile["tables"]
    css = tables["css"]
    html = tables["html"]
    svg = tables["svg"]
    out = [
        "// Generated by IDL/generate-profile-tables.py from third-party/widget-sandbox/profile/profile.json (profile %d)."
        % profile["profile"],
        "// Do not edit: change the vendored JSON and run the generator. Included by Sources/Host/Profile.cpp.",
        "",
        array("kCSSProperties", css["properties"]),
        array("kCSSFunctions", css["functions"]),
        array("kCSSUnits", css["units"]),
        # css.values, every property's keyword set (display, position, user-select, …) as "property:keyword".
        array("kCSSValueSets", [p + ":" + v for p, values in css["values"].items() for v in values]),
        array("kCSSValuedProperties", css["values"].keys()),
        array("kCSSPositionRewrites", css["rewrite"]["position"].keys()),
        array("kCSSOverflowRewrites", css["rewrite"]["overflow"].keys()),
        array("kCSSFilterFunctions", css["filterFunctions"]),
        array("kCSSTransform3D", css["transform3d"]),
        array("kCSSGenericFonts", css["fonts"]["generic"]),
        array("kCSSPseudoClasses", list(css["pseudoClasses"]) + list(css["pseudoRewrite"].keys())),
        array("kCSSPseudoElements", css["pseudoElements"]),
        array("kImageTypes", tables["images"]),
        array("kCSSAtRules", css["atRules"]),
        array("kCSSMediaTypes", css["mediaTypes"]),
        array("kCSSMediaFeatures", css["mediaFeatures"]),
        array("kHTMLAttributes", [a.lower() for a in html["attributes"]]),
        array("kHTMLAttributePrefixes", html["attributePrefixes"]),
        array("kSVGElements", [e.lower() for e in svg["elements"]]),
        array("kSVGAttributes", [a.lower() for a in svg["attributes"]]),
        array("kTextAttributes", TEXT_ATTRIBUTES),
        array("kCSSValuedSVGAttributes", CSS_VALUED_SVG_ATTRIBUTES),
        pairs("kSVGElementNames", [(e.lower(), e) for e in svg["elements"]]),
        pairs("kSVGAttributeNames", [(a.lower(), a) for a in svg["attributes"]]),
        pairs("kHTMLElementActions", list(html["elements"].items()), "ElementAction", lambda v: ACTIONS[v]),
        "inline constexpr ElementAction kUnknownHTMLAction = %s;" % ACTIONS[html["unknown"]],
        pairs("kFontAliases", css["fonts"]["aliases"].items()),
        pairs("kFontFallbacks", css["fonts"]["fallback"].items()),
        'inline constexpr std::string_view kDefaultFont = "%s";' % css["fonts"]["default"],
        pairs("kPseudoRewrites", css["pseudoRewrite"].items()),
        pairs("kPositionRewrites", css["rewrite"]["position"].items()),
        pairs("kOverflowRewrites", css["rewrite"]["overflow"].items()),
        "",
        "// The renderer's UA layer (SDK v1 §2.4: the root, the text elements and the default <button>), for the master sheet",
        "// (Builder's masterWithHostCSS).",
        'inline constexpr std::string_view kUAStylesheet = "%s";' % ua_stylesheet(tables["uaStylesheet"]).replace("\\", "\\\\").replace('"', '\\"'),
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
