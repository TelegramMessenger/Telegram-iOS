"""Writes the candidate skip list for WidgetRuntimeWPTTests (M1b plan, Task 17) from the vendored WPT tree.

    python3 -I make-skip-list.py <repo>/third-party/wpt > <WidgetRuntime>/wpt-skip.txt

Every page the runner would run (the runner's discovery rules, approximated) is checked against REASONS in order,
and the first match skips the file, with the matched text as the note. The patterns are heuristics and a skipped
test is coverage lost, so the output is reviewed by hand (Task 17, Step 7) before it is committed.
"""
import os
import re
import sys

DIRS = ['dom/nodes', 'dom/events', 'dom/collections', 'dom/lists', 'html/webappapis/timers',
        'html/webappapis/microtask-queuing', 'html/webappapis/animation-frames', 'html/webappapis/scripting/event-loops']
NOT_TESTS = {'resources', 'support', 'crashtests', 'tools'}
REASONS = [
    ('testdriver', r'testdriver|test_driver'),
    ('server', r'\bfetch\(|XMLHttpRequest|new (?:Shared)?Worker\(|serviceWorker|\.py\b|/common/get-host-info'),
    ('iframe', r'<iframe|createElement\(\s*["\']iframe|\.contentWindow\b|\.contentDocument\b|window\.frames\b|\bframes\[|window\.open\('),
    ('second-document', r'document\.implementation|createHTMLDocument|createDocument\(|DOMParser|XMLSerializer'),
    ('out-of-IDL', r'attachShadow|\.shadowRoot\b|shadowrootmode'),
]
HEADER = """# Tests WidgetRuntimeWPTTests does not run (M1b plan, Task 17). One per line, three tab-separated fields:
#   <test>  <reason>  <note>
# <test> is a path under third-party/wpt, optionally with a variant ("dom/x.html?1"); without one it covers every
# variant. <reason> is one of: iframe, second-document, testdriver, server (wptserve handlers, fetch, workers),
# out-of-IDL (shadow DOM; XHTML, which needs an XML parser), bug (a runtime defect that crashes or hangs the runner;
# the note names the ledger ruling; none may remain at the end of M1b's final review).
# Generated by Tests/WPT/make-skip-list.py, then reviewed by hand."""


def is_test(name, text):
    if '-manual.' in name:
        return False
    if name.endswith(('.any.js', '.window.js')):
        globals_ = re.findall(r'^//\s*META:\s*global=(.*)$', text, re.M)
        return not globals_ or any(t.strip() in ('window', 'default') for t in globals_[0].split(','))
    return name.endswith(('.html', '.htm', '.xhtml', '.xht')) and '/resources/testharness.js' in text


def main():
    root = sys.argv[1]
    lines = []
    for d in DIRS:
        for base, dirs, files in os.walk(os.path.join(root, d)):
            dirs[:] = sorted(x for x in dirs if x not in NOT_TESTS)
            for name in sorted(files):
                path = os.path.join(base, name)
                if os.path.islink(path):
                    continue
                text = open(path, encoding='utf-8', errors='replace').read()
                if not is_test(name, text):
                    continue
                rel = os.path.relpath(path, root)
                reason = note = None
                if '.sub.' in name or '.https.' in name:
                    reason, note = 'server', 'wptserve substitution or https'
                elif name.endswith(('.xhtml', '.xht')):
                    reason, note = 'out-of-IDL', 'XHTML: no XML parser (spec 10.3)'
                else:
                    for r, pattern in REASONS:
                        m = re.search(pattern, text)
                        if m:
                            reason, note = r, 'matches ' + repr(m.group(0))[:60]
                            break
                if reason:
                    lines.append('%s\t%s\t%s' % (rel, reason, note))
    print(HEADER)
    for line in sorted(lines):
        print(line)


main()
