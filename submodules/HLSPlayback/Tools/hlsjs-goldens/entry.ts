// Runs hls.js v1.7.3's own code on fixed inputs and prints Tests/HLSJSGoldens.swift.
// Bundled and run by generate.sh from the root of an hls.js checkout.
import AbrController from './src/controller/abr-controller';
import EwmaBandWidthEstimator from './src/utils/ewma-bandwidth-estimator';

type Sample = [durationMs: number, bytes: number];

const lines: string[] = [];
const emit = (line: string) => lines.push(line);

const double = (value: number): string => {
  if (!Number.isFinite(value)) {
    throw new Error(`non-finite golden value ${value}`);
  }
  return value.toPrecision(17);
};

// Estimator: hls.js's VoD half-lives (slow 9 s, fast 3 s), the 500 kbit/s default and the 100 ms TTFB default.
const estimatorInputs: Sample[][] = [
  // One 2 MB sample in 25 ms (hits the duration floor's cap).
  [[25, 2_000_000]],
  // Ten 400 KB samples at 1 s each.
  Array.from({ length: 10 }, (): Sample => [1000, 400_000]),
  // A 5 MB sample in 10 ms, then three 500 KB samples at 2 s.
  [
    [10, 5_000_000],
    [2000, 500_000],
    [2000, 500_000],
    [2000, 500_000],
  ],
  // Zero-byte and 1-byte samples.
  [
    [100, 0],
    [100, 1],
    [0, 1],
  ],
  // Alternating 100 KB at 50 ms and 1 MB at 4 s.
  [
    [50, 100_000],
    [4000, 1_000_000],
    [50, 100_000],
    [4000, 1_000_000],
    [50, 100_000],
    [4000, 1_000_000],
  ],
];

emit('// Generated by Tools/hlsjs-goldens/generate.sh from hls.js v1.7.3');
emit('// (e5ff3583965e3af16c4a4b4d2b5f7bd1ffb5b7de). Do not edit by hand: regenerate.');
emit('');
emit('enum HLSJSGoldens {');
emit('    struct EstimatorCase {');
emit('        let samples: [(durationMs: Double, bytes: Int64)]');
emit('        let estimates: [Double]');
emit('    }');
emit('');
emit('    static let estimatorCases: [EstimatorCase] = [');
for (const samples of estimatorInputs) {
  const estimator = new EwmaBandWidthEstimator(9, 3, 500_000, 100);
  const estimates: number[] = [];
  for (const [durationMs, bytes] of samples) {
    estimator.sample(durationMs, bytes);
    estimates.push(estimator.getEstimate());
  }
  emit('        EstimatorCase(');
  emit(`            samples: [${samples.map(([d, b]) => `(durationMs: ${double(d)}, bytes: ${b})`).join(', ')}],`);
  emit(`            estimates: [${estimates.map(double).join(', ')}]`);
  emit('        ),');
}
emit('    ]');

// ABR: hls.js's AbrController over a stand-in `hls` with our stream shape: levels sorted by height, no
// CODECS, FRAME-RATE or VIDEO-RANGE, BANDWIDTH = maxBitrate = averageBitrate, firstLevel = the top level (the master
// lists the highest quality first), no media capabilities, VoD.
type LevelSpec = [height: number, width: number, bandwidth: number];
const levelSets: LevelSpec[][] = [
  [
    [360, 640, 290_000],
    [480, 854, 600_000],
    [720, 1280, 1_200_000],
    [1080, 1920, 1_650_000],
  ],
  [[720, 1280, 1_200_000]],
];
const bandwidths = [2e5, 5e5, 8e5, 1.3e6, 2e6, 5e6];
const lastLoadedLevels = [-1, 0, 1, 2, 3];
const starvationDelays = [0, 2, 10, 60];
const maxStarvationDelays = [0, 4];
const factorPairs: [number, number][] = [
  [0.95, 0.7],
  [1, 1],
];
const maxAutoLevels = [0, 1, 3];
const segmentDuration = 5;

const noop = () => {};
const quietLogger = { trace: noop, debug: noop, log: noop, warn: noop, info: noop, error: noop };

// Per-level inputs the base grid keeps fixed: segment durations, load errors, the last playlist load time.
type LevelVariation = {
  durations?: number[];
  fragDuration?: number;
  errors?: number[];
  lastLevelLoadSec?: number;
  missingDetails?: number[];
};

const makeAbr = (
  levelSet: LevelSpec[],
  detailsLoaded: boolean,
  lastLoaded: number,
  maxAutoLevel: number,
  starvationDelay: number,
  bandwidth: number,
  variation: LevelVariation = {},
) => {
  const levels = levelSet.map(([height, width, bitrate], index) => ({
    bitrate,
    maxBitrate: bitrate,
    averageBitrate: bitrate,
    realBitrate: 0,
    height,
    width,
    codecSet: '',
    codecs: '',
    videoRange: 'SDR',
    frameRate: 0,
    loadError: variation.errors?.[index] ?? 0,
    fragmentError: 0,
    details:
      detailsLoaded && !(variation.missingDetails ?? []).includes(index)
        ? { averagetargetduration: variation.durations?.[index] ?? segmentDuration, live: false }
        : undefined,
  }));
  const loadLevel = lastLoaded;
  const hls: any = {
    logger: quietLogger,
    config: {
      abrEwmaFastVoD: 3,
      abrEwmaSlowVoD: 9,
      abrEwmaFastLive: 3,
      abrEwmaSlowLive: 9,
      abrEwmaDefaultEstimate: 500_000,
      abrBandWidthFactor: 0.95,
      abrBandWidthUpFactor: 0.7,
      maxStarvationDelay: 4,
      maxLoadingDelay: 4,
      errorPenaltyExpireMs: 0,
      useMediaCapabilities: false,
      audioPreference: undefined,
      videoPreference: undefined,
    },
    levels,
    allAudioTracks: [],
    loadLevel,
    loadLevelObj: loadLevel >= 0 ? levels[loadLevel] : null,
    latestLevelDetails: loadLevel >= 0 ? levels[loadLevel].details ?? null : null,
    firstLevel: levels.length - 1,
    minAutoLevel: 0,
    maxAutoLevel,
    autoLevelEnabled: true,
    media: { playbackRate: 1, paused: false, readyState: 4 },
    mainForwardBufferInfo: { len: starvationDelay },
    on: noop,
    off: noop,
    trigger: noop,
  };
  const abr: any = new AbrController(hls);
  abr.lastLoadedFragLevel = lastLoaded;
  abr.fragCurrent = { duration: variation.fragDuration ?? segmentDuration, level: lastLoaded };
  abr.lastLevelLoadSec = variation.lastLevelLoadSec ?? 0;
  abr.firstSelection = -1;
  abr.bwEstimator = {
    getEstimate: () => bandwidth,
    getEstimateTTFB: () => 100,
    canEstimate: () => true,
  };
  return abr;
};

// One case per line: levelSet bandwidth lastLoaded bufferStarvationDelay maxStarvationDelay bandwidthFactor upFactor
// detailsLoaded maxAutoLevel expected (-1 = none).
const findBestLevelRows: string[] = [];
// One case per line: levelSet bandwidth lastLoaded bufferStarvationDelay detailsLoaded maxAutoLevel expected. Only
// cases with a loaded segment: before one, hls.js's getter takes its firstAutoLevel path, which D12 replaces.
const nextAutoLevelRows: string[] = [];
levelSets.forEach((levelSet, levelSetIndex) => {
  for (const bandwidth of bandwidths) {
    for (const lastLoaded of lastLoadedLevels) {
      if (lastLoaded >= levelSet.length) {
        continue;
      }
      for (const maxAutoLevel of maxAutoLevels) {
        if (maxAutoLevel >= levelSet.length || (levelSet.length > 1 && maxAutoLevel === 0)) {
          continue;
        }
        for (const detailsLoaded of [true, false]) {
          for (const starvationDelay of starvationDelays) {
            for (const maxStarvationDelay of maxStarvationDelays) {
              for (const [bandwidthFactor, upFactor] of factorPairs) {
                const abr = makeAbr(levelSet, detailsLoaded, lastLoaded, maxAutoLevel, starvationDelay, bandwidth);
                const result = abr.findBestLevel(
                  bandwidth,
                  0,
                  maxAutoLevel,
                  starvationDelay,
                  maxStarvationDelay,
                  bandwidthFactor,
                  upFactor,
                );
                findBestLevelRows.push(
                  [levelSetIndex, bandwidth, lastLoaded, starvationDelay, maxStarvationDelay, bandwidthFactor, upFactor, detailsLoaded ? 1 : 0, maxAutoLevel, result].join(' '),
                );
              }
            }
            if (lastLoaded >= 0) {
              const abr = makeAbr(levelSet, detailsLoaded, lastLoaded, maxAutoLevel, starvationDelay, bandwidth);
              const result = abr.nextAutoLevel;
              nextAutoLevelRows.push(
                [levelSetIndex, bandwidth, lastLoaded, starvationDelay, detailsLoaded ? 1 : 0, maxAutoLevel, result].join(' '),
              );
            }
          }
        }
      }
    }
  }
});

emit('');
emit('    // Level sets, by index: [height, width, bandwidth].');
emit('    static let levelSets: [[(height: Int, width: Int, bandwidth: Int)]] = [');
for (const levelSet of levelSets) {
  emit(`        [${levelSet.map(([h, w, b]) => `(height: ${h}, width: ${w}, bandwidth: ${b})`).join(', ')}],`);
}
emit('    ]');
emit(`    static let segmentDuration: Double = ${double(segmentDuration)}`);
emit('');
emit('    // levelSet bandwidth lastLoaded bufferStarvationDelay maxStarvationDelay bandwidthFactor upFactor detailsLoaded maxAutoLevel expected');
emit('    static let findBestLevelTable = """');
findBestLevelRows.forEach((row) => emit(row));
emit('"""');
emit('');
emit('    // levelSet bandwidth lastLoaded bufferStarvationDelay detailsLoaded maxAutoLevel expected');
emit('    static let nextAutoLevelTable = """');
nextAutoLevelRows.forEach((row) => emit(row));
emit('"""');

// The same two functions on the four-level set, over what the grid above keeps fixed: segment durations (2 s,
// fractional, different per level, with the current fragment's duration that of the level on screen), load errors on a
// level, and a cap of 0.
type DurationProfile = { name: number; durations: number[] };
const durationProfiles: DurationProfile[] = [
  { name: 0, durations: [2, 2, 2, 2] },
  { name: 1, durations: [4.83333, 4.83333, 4.83333, 4.83333] },
  { name: 2, durations: [6, 5, 4, 2] },
];
const errorMasks = [0, 1 << 2, 1 << 3];
const variedBandwidths = [5e5, 1.3e6, 5e6];
const variedLastLoaded = [-1, 1, 2, 3];
const variedCaps = [0, 1, 3];
const variedStarvationDelays = [0, 10];
const fourLevels = levelSets[0];
const errorsFor = (mask: number) => fourLevels.map((_, index) => ((mask >> index) & 1 ? 1 : 0));
const findBestLevelVariedRows: string[] = [];
const nextAutoLevelVariedRows: string[] = [];
for (const profile of durationProfiles) {
  for (const mask of errorMasks) {
    for (const maxAutoLevel of variedCaps) {
      for (const bandwidth of variedBandwidths) {
        for (const lastLoaded of variedLastLoaded) {
          const variation: LevelVariation = {
            durations: profile.durations,
            fragDuration: profile.durations[Math.max(lastLoaded, 0)],
            errors: errorsFor(mask),
          };
          for (const starvationDelay of variedStarvationDelays) {
            for (const maxStarvationDelay of maxStarvationDelays) {
              const abr = makeAbr(fourLevels, true, lastLoaded, maxAutoLevel, starvationDelay, bandwidth, variation);
              const result = abr.findBestLevel(bandwidth, 0, maxAutoLevel, starvationDelay, maxStarvationDelay, 0.95, 0.7);
              findBestLevelVariedRows.push([profile.name, mask, maxAutoLevel, bandwidth, lastLoaded, starvationDelay, maxStarvationDelay, result].join(' '));
            }
            if (lastLoaded >= 0) {
              const abr = makeAbr(fourLevels, true, lastLoaded, maxAutoLevel, starvationDelay, bandwidth, variation);
              nextAutoLevelVariedRows.push([profile.name, mask, maxAutoLevel, bandwidth, lastLoaded, starvationDelay, abr.nextAutoLevel].join(' '));
            }
          }
        }
      }
    }
  }
}

emit('');
emit('    // Segment duration profiles, by index: per level, and the current fragment is the level on screen\'s.');
emit('    static let durationProfiles: [[Double]] = [');
for (const profile of durationProfiles) {
  emit(`        [${profile.durations.map(double).join(', ')}],`);
}
emit('    ]');
emit('');
emit('    // Four-level set. profile errorMask maxAutoLevel bandwidth lastLoaded bufferStarvationDelay maxStarvationDelay expected; factors 0.95 / 0.7');
emit('    static let findBestLevelVariedTable = """');
findBestLevelVariedRows.forEach((row) => emit(row));
emit('"""');
emit('');
emit('    // Four-level set. profile errorMask maxAutoLevel bandwidth lastLoaded bufferStarvationDelay expected');
emit('    static let nextAutoLevelVariedTable = """');
nextAutoLevelVariedRows.forEach((row) => emit(row));
emit('"""');

// The abandon rule: hls.js's _abandonRulesCheck on the four-level set, in Auto, while playing. The port's deviation D2
// is modelled on the hls.js side so the rest is compared exactly: the TTFB is the fixed 100 ms estimate (the load's own
// TTFB is set to it, and TTFB samples are ignored), and a bandwidth sample covers the whole load (the 100 ms hls.js
// subtracts is added back).
(globalThis as any).self = globalThis;
const fixedTTFB = 100;
const wrapEstimator = (real: EwmaBandWidthEstimator) => ({
  sample: (durationMs: number, bytes: number) => real.sample(durationMs + fixedTTFB, bytes),
  sampleTTFB: noop,
  getEstimate: () => real.getEstimate(),
  getEstimateTTFB: () => fixedTTFB,
  canEstimate: () => real.canEstimate(),
});
// Estimator histories, by index: samples [durationMs, bytes] before the check.
const estimatorHistories: Sample[][] = [[], [[1000, 250_000]], [[1000, 50_000], [1000, 50_000]]];
// Variants, by index: every playlist loaded; level 1's playlist not loaded and a 0.4 s playlist load time.
const abandonVariants: LevelVariation[] = [{}, { missingDetails: [1], lastLevelLoadSec: 0.4 }];
const abandonRows: string[] = [];
estimatorHistories.forEach((history, historyIndex) => {
  for (const fragLevel of [1, 2, 3]) {
    for (const duration of [5, 2]) {
      for (const expectedFactor of [1, 1.6]) {
        for (const loadedFraction of [0, 0.02, 0.2, 0.6]) {
          for (const elapsedMs of [1500, 4000]) {
            for (const starvationDelay of [0, 2, 8]) {
              for (const rate of [1, 2]) {
                abandonVariants.forEach((variant, variantIndex) => {
                  const bitrate = fourLevels[fragLevel][2];
                  const expectedBytes = Math.round((duration * bitrate * expectedFactor) / 8);
                  const loadedBytes = Math.round(expectedBytes * loadedFraction);
                  const levels = fourLevels.map(([height, width, levelBitrate], index) => ({
                    bitrate: levelBitrate,
                    maxBitrate: levelBitrate,
                    averageBitrate: levelBitrate,
                    realBitrate: 0,
                    height,
                    width,
                    codecSet: '',
                    codecs: '',
                    videoRange: 'SDR',
                    frameRate: 0,
                    loadError: 0,
                    fragmentError: 0,
                    details: (variant.missingDetails ?? []).includes(index) ? undefined : { averagetargetduration: duration, live: false },
                  }));
                  let loadLevel = fragLevel;
                  let chosen = -1;
                  let resetTo = 0;
                  let abr: any;
                  const hls: any = {
                    logger: quietLogger,
                    config: {
                      abrEwmaFastVoD: 3,
                      abrEwmaSlowVoD: 9,
                      abrEwmaFastLive: 3,
                      abrEwmaSlowLive: 9,
                      abrEwmaDefaultEstimate: 500_000,
                      abrBandWidthFactor: 0.95,
                      abrBandWidthUpFactor: 0.7,
                      maxStarvationDelay: 4,
                      maxLoadingDelay: 4,
                      errorPenaltyExpireMs: 0,
                      useMediaCapabilities: false,
                    },
                    levels,
                    allAudioTracks: [],
                    get loadLevel() {
                      return loadLevel;
                    },
                    get loadLevelObj() {
                      return levels[loadLevel];
                    },
                    latestLevelDetails: { averagetargetduration: duration, live: false },
                    firstLevel: 3,
                    minAutoLevel: 0,
                    maxAutoLevel: 3,
                    autoLevelEnabled: true,
                    media: { playbackRate: rate, paused: false, readyState: 4 },
                    mainForwardBufferInfo: { len: starvationDelay * rate },
                    // The level controller sets the load level at once, then the ABR's next level.
                    set nextLoadLevel(n: number) {
                      chosen = n;
                      loadLevel = n;
                      abr.nextAutoLevel = n;
                    },
                    set nextAutoLevel(n: number) {
                      abr.nextAutoLevel = n;
                    },
                    on: noop,
                    off: noop,
                    trigger: noop,
                  };
                  abr = new AbrController(hls);
                  const real = new EwmaBandWidthEstimator(9, 3, 500_000, fixedTTFB);
                  for (const [d, b] of history) {
                    real.sample(d, b);
                  }
                  abr.bwEstimator = wrapEstimator(real);
                  abr.initEstimator = () => wrapEstimator(new EwmaBandWidthEstimator(9, 3, hls.config.abrEwmaDefaultEstimate, fixedTTFB));
                  const resetEstimator = abr.resetEstimator.bind(abr);
                  abr.resetEstimator = (value?: number) => {
                    resetTo = value ?? 0;
                    resetEstimator(value);
                  };
                  abr.lastLoadedFragLevel = fragLevel;
                  abr.lastLevelLoadSec = variant.lastLevelLoadSec ?? 0;
                  const now = performance.now();
                  abr.fragCurrent = {
                    sn: 7,
                    level: fragLevel,
                    duration,
                    bitrate: (expectedBytes * 8) / duration,
                    type: 'main',
                    stats: {
                      aborted: false,
                      loaded: loadedBytes,
                      total: expectedBytes,
                      loading: { start: now - elapsedMs, first: loadedBytes > 0 ? now - elapsedMs + fixedTTFB : 0 },
                    },
                    abortRequests: noop,
                  };
                  abr.timer = 1;
                  abr._abandonRulesCheck();
                  abr.clearTimer();
                  const estimate = abr.bwEstimator.getEstimate();
                  abandonRows.push(
                    [historyIndex, fragLevel, duration, expectedBytes, loadedBytes, elapsedMs, starvationDelay, rate, variantIndex, chosen, resetTo, double(estimate)].join(' '),
                  );
                });
              }
            }
          }
        }
      }
    }
  }
});

emit('');
emit('    // Abandon estimator histories, by index: samples before the check.');
emit('    static let abandonHistories: [[(durationMs: Double, bytes: Int64)]] = [');
for (const history of estimatorHistories) {
  emit(`        [${history.map(([d, b]) => `(durationMs: ${double(d)}, bytes: ${b})`).join(', ')}],`);
}
emit('    ]');
emit('');
emit('    // Four-level set, TTFB fixed at 100 ms (D2 modelled on the hls.js side). history fragLevel duration expectedBytes');
emit('    // loadedBytes elapsedMs bufferStarvationDelay rate variant(0 all playlists, 1 level 1 without one and a 0.4 s');
emit('    // playlist load) level(-1 none) resetTo(0 none) estimate');
emit('    static let abandonTable = """');
abandonRows.forEach((row) => emit(row));
emit('"""');
emit('}');

console.log(lines.join('\n'));
