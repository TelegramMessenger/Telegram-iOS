import Foundation

/// A test file that reads every field of every payload constructor through its Swift accessor,
/// so AccessorProbeTests can compare the Swift-side offsets with the table-driven description.
enum AccessorProbeGenerator {
    static func generate(apiPrefix: String, layout: TLSchemaLayout) -> String {
        var out = "// Generated by SwiftTL. Do not edit.\nimport Foundation\n@testable import TelegramApi\n\n"
        out += "/// Every field of every payload constructor, read through its Swift accessor.\n"
        out += "let schemaAccessorProbes: [String: (Any) -> [(String, Any?)]] = [\n"
        for type in layout.types {
            for constructor in type.constructors where !constructor.fields.isEmpty {
                let name = constructor.constructor.name.value
                out += "    \"\(type.type.name).\(name)\": { value in\n"
                out += "        guard case let .\(name)(d) = value as! \(apiPrefix).\(type.type.name) else { preconditionFailure() }\n"
                let fields = constructor.fields.map { "(\"\($0.descriptionName)\", d.\($0.descriptionName) as Any?)" }
                out += "        return [\(fields.joined(separator: ", "))]\n"
                out += "    },\n"
            }
        }
        out += "]\n"
        return out
    }
}
